<?php

const ORION_PLAYER_PETITION_SIGNATURE_THRESHOLD = 50;
const ORION_PLAYER_PETITION_VOTING_DAYS = 3;
const ORION_PLAYER_PETITION_COOLDOWN_DAYS = 3;

function ensure_player_petition_schema($pdo) {
    $pdo->exec("CREATE TABLE IF NOT EXISTS player_petitions (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        author_account_id BIGINT NOT NULL,
        title VARCHAR(180) NOT NULL,
        description TEXT NOT NULL,
        expected_result TEXT NOT NULL,
        status VARCHAR(32) NOT NULL DEFAULT 'collecting',
        signature_count INTEGER NOT NULL DEFAULT 0,
        signature_threshold INTEGER NOT NULL DEFAULT 50,
        gso_proposal_id BIGINT NULL,
        submitted_ip VARCHAR(45) NULL,
        promoted_at TIMESTAMP NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (id)
    )");
    $pdo->exec("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uniq_player_petition_gso') THEN ALTER TABLE player_petitions ADD CONSTRAINT uniq_player_petition_gso UNIQUE (gso_proposal_id); END IF; END $$");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_player_petitions_status ON player_petitions (status, created_at)");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_player_petitions_author ON player_petitions (author_account_id, created_at)");
    $pdo->exec("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_player_petitions_updated_at') THEN CREATE TRIGGER trg_player_petitions_updated_at BEFORE UPDATE ON player_petitions FOR EACH ROW EXECUTE FUNCTION update_updated_at_column(); END IF; END $$");

    $pdo->exec("CREATE TABLE IF NOT EXISTS player_petition_signatures (
        petition_id BIGINT NOT NULL,
        account_id BIGINT NOT NULL,
        ip_address VARCHAR(45) NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (petition_id, account_id)
    )");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_player_petition_signatures_account ON player_petition_signatures (account_id, created_at)");
}

function player_petition_text_length($value) {
    return function_exists('mb_strlen') ? mb_strlen((string)$value, 'UTF-8') : strlen((string)$value);
}

function player_petition_signature_progress($signature_count, $signature_threshold = ORION_PLAYER_PETITION_SIGNATURE_THRESHOLD) {
    $signature_count = max(0, intval($signature_count));
    $signature_threshold = max(1, intval($signature_threshold));
    return min(100, max(0, (int)round(($signature_count / $signature_threshold) * 100)));
}

function player_petition_has_reached_threshold($signature_count, $signature_threshold = ORION_PLAYER_PETITION_SIGNATURE_THRESHOLD) {
    return intval($signature_count) >= max(1, intval($signature_threshold));
}

function player_petition_status_from_gso_status($status) {
    $status = (string)$status;
    if (in_array($status, ['voting', 'council_review', 'implementation', 'implemented'], true)) {
        return $status;
    }
    if (in_array($status, ['rejected_vote', 'rejected_head'], true)) {
        return 'rejected';
    }
    return null;
}

