function ensure_gso_schema($pdo) {
    $pdo->exec("CREATE TABLE IF NOT EXISTS gso_proposals (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        author_account_id BIGINT NOT NULL,
        title VARCHAR(180) NOT NULL,
        description TEXT NOT NULL,
        expected_result TEXT NOT NULL,
        status VARCHAR(32) NOT NULL DEFAULT 'voting',
        eligible_voters INTEGER NOT NULL DEFAULT 1,
        quorum_required INTEGER NOT NULL DEFAULT 1,
        voting_duration_days SMALLINT NOT NULL DEFAULT 3,
        voting_ends_at TIMESTAMP NOT NULL,
        vote_closed_at TIMESTAMP NULL,
        vote_result VARCHAR(16) NULL,
        vote_round INTEGER NOT NULL DEFAULT 1,
        head_rejection_count SMALLINT NOT NULL DEFAULT 0,
        head_account_id BIGINT NULL,
        head_decision VARCHAR(16) NULL,
        head_note TEXT NULL,
        head_decided_at TIMESTAMP NULL,
        implementation_status VARCHAR(20) NOT NULL DEFAULT 'none',
        implementation_note TEXT NULL,
        implemented_by BIGINT NULL,
        implemented_at TIMESTAMP NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (id)
    )");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_proposals_status ON gso_proposals (status, created_at)");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_proposals_author ON gso_proposals (author_account_id)");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_proposals_vote_end ON gso_proposals (status, voting_ends_at)");
    $pdo->exec("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_gso_proposals_updated_at') THEN CREATE TRIGGER trg_gso_proposals_updated_at BEFORE UPDATE ON gso_proposals FOR EACH ROW EXECUTE FUNCTION update_updated_at_column(); END IF; END $$");

    $pdo->exec("CREATE TABLE IF NOT EXISTS gso_votes (
        proposal_id BIGINT NOT NULL,
        vote_round INTEGER NOT NULL DEFAULT 1,
        account_id BIGINT NOT NULL,
        choice VARCHAR(12) NOT NULL,
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (proposal_id, vote_round, account_id)
    )");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_votes_account ON gso_votes (account_id, updated_at)");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_votes_choice ON gso_votes (proposal_id, vote_round, choice)");
    $pdo->exec("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_gso_votes_updated_at') THEN CREATE TRIGGER trg_gso_votes_updated_at BEFORE UPDATE ON gso_votes FOR EACH ROW EXECUTE FUNCTION update_updated_at_column(); END IF; END $$");

    $pdo->exec("CREATE TABLE IF NOT EXISTS gso_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        proposal_id BIGINT NOT NULL,
        actor_account_id BIGINT NULL,
        event_type VARCHAR(32) NOT NULL,
        detail VARCHAR(255) NOT NULL DEFAULT '',
        metadata_json TEXT NULL,
        visibility VARCHAR(16) NOT NULL DEFAULT 'public',
        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
        PRIMARY KEY (id)
    )");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_events_proposal ON gso_events (proposal_id, created_at)");
    $pdo->exec("CREATE INDEX IF NOT EXISTS idx_gso_events_actor ON gso_events (actor_account_id, created_at)");

    if (!db_column_exists($pdo, 'gso_proposals', 'voting_duration_days')) {
        $pdo->exec("ALTER TABLE gso_proposals ADD COLUMN voting_duration_days SMALLINT NOT NULL DEFAULT 3");
    }
    if (!db_column_exists($pdo, 'gso_proposals', 'vote_round')) {
        $pdo->exec("ALTER TABLE gso_proposals ADD COLUMN vote_round INTEGER NOT NULL DEFAULT 1");
    }
    if (!db_column_exists($pdo, 'gso_proposals', 'head_rejection_count')) {
        $pdo->exec("ALTER TABLE gso_proposals ADD COLUMN head_rejection_count SMALLINT NOT NULL DEFAULT 0");
    }
    if (!db_column_exists($pdo, 'gso_events', 'visibility')) {
        $pdo->exec("ALTER TABLE gso_events ADD COLUMN visibility VARCHAR(16) NOT NULL DEFAULT 'public'");
    }
    if (!db_column_exists($pdo, 'gso_votes', 'vote_round')) {
        $pdo->exec("ALTER TABLE gso_votes ADD COLUMN vote_round INTEGER NOT NULL DEFAULT 1");
    }

    // Проверяем состав первичного ключа gso_votes через pg_constraint
    $primary_columns = [];
    $stmt = $pdo->prepare("SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) WHERE i.indrelid = 'gso_votes'::regclass AND i.indisprimary ORDER BY array_position(i.indkey, a.attnum)");
    $stmt->execute();
    foreach ($stmt->fetchAll() as $row) {
        $primary_columns[] = $row['attname'];
    }
    if ($primary_columns !== ['proposal_id', 'vote_round', 'account_id']) {
        $pdo->exec("ALTER TABLE gso_votes DROP CONSTRAINT IF EXISTS gso_votes_pkey");
        $pdo->exec("ALTER TABLE gso_votes ADD PRIMARY KEY (proposal_id, vote_round, account_id)");
    }
    $has_round_choice_index = false;
    $idx_stmt = $pdo->prepare("SELECT 1 FROM pg_indexes WHERE indexname = 'idx_gso_votes_round_choice'");
    $idx_stmt->execute();
    $has_round_choice_index = $idx_stmt->fetch() !== false;
    if (!$has_round_choice_index) {
        $pdo->exec("CREATE INDEX idx_gso_votes_round_choice ON gso_votes (proposal_id, vote_round, choice)");
    }
}

