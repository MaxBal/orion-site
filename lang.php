// Класс «кириллическая буква» для границ слова (чтобы «Вход» не ловился внутри
// «Входите» и т.п.).
const I18N_CYR = 'А-Яа-яЁёІіЇїЄєҐґ';

// Компилирует словарь в несколько regex-блоков, чтобы не упереться в лимит
// размера PCRE по мере роста переводов. Вызов без аргумента сохраняет старый
// контракт и компилирует RU→UK.
function i18n_compiled($lang = null) {
    $lang = $lang === null ? 'uk' : i18n_locale_code($lang);
    static $cache = [];
    if (isset($cache[$lang])) {
        return $cache[$lang];
    }
    $map = $lang === 'en' ? i18n_en_map() : i18n_uk_map();
    $keys = array_keys($map);
    // Длинные фразы — первыми, чтобы они выигрывали в альтернации regex.
    usort($keys, function ($a, $b) {
        return mb_strlen($b, 'UTF-8') - mb_strlen($a, 'UTF-8');
    });
    $chunks = [];
    foreach (array_chunk($keys, 80) as $key_chunk) {
        $norm = [];
        $parts = [];
        foreach ($key_chunk as $k) {
            $nk = preg_replace('/\s+/u', ' ', trim($k));
            $norm[$nk] = $map[$k];
            $esc = preg_quote($k, '/');
            // Любая последовательность пробелов в исходнике (включая переносы
            // строк и отступы) — матчим как \s+.
            $esc = preg_replace('/(\\\\?\s)+/u', '\\\\s+', $esc);
            $parts[] = $esc;
        }
        $chunks[] = [
            '/(?<![' . I18N_CYR . '])(?:' . implode('|', $parts) . ')(?![' . I18N_CYR . '])/u',
            $norm,
        ];
    }
    $cache[$lang] = $chunks;
    return $cache[$lang];
}

function i18n_replace_compiled($text, $lang) {
    $out = (string)$text;
    $replacements = [];
    $counter = 0;

    foreach (i18n_compiled($lang) as $compiled) {
        list($re, $norm) = $compiled;
        $next = preg_replace_callback($re, function ($m) use ($norm, &$replacements, &$counter) {
            $key = preg_replace('/\s+/u', ' ', trim($m[0]));
            if (!array_key_exists($key, $norm)) {
                return $m[0];
            }
            // Плейсхолдер не даёт коротким фразам из следующих блоков повторно
            // перевести часть уже найденной длинной фразы.
            $token = "\x1AORION_I18N_" . $counter++ . "\x1A";
            $replacements[$token] = $norm[$key];
            return $token;
        }, $out);
        if ($next === null) {
            return $text;
        }
        $out = $next;
    }

    return $replacements ? strtr($out, $replacements) : $out;
}

// Сохраняет содержимое отмеченных авторских блоков до запуска regex-фильтра.
// Вложенная разметка внутри обычного блока остаётся нетронутой.
function i18n_protect_ignored_html($html, &$protected) {
    $html = (string)$html;
    $void_tags = array_fill_keys([
        'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input',
        'keygen', 'link', 'meta', 'param', 'source', 'track', 'wbr',
    ], true);
    $is_ignored_start = static function ($attrs) {
        $attrs = trim((string)$attrs);
        $attrs = preg_replace('/\/\s*$/', '', $attrs) ?? $attrs;
        if (preg_match('/(?:^|\s)data-i18n-ignore(?:\s*=\s*(?:"[^"]*"|\'[^\']*\'|[^\s>]+))?(?=\s|$)/i', $attrs) === 1) {
            return true;
        }
        if (preg_match('/(?:^|\s)translate\s*=\s*(?:"no"|\'no\'|no)(?=\s|$)/i', $attrs) === 1) {
            return true;
        }
        $class_value = '';
        if (preg_match('/(?:^|\s)class\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s>]+))/i', $attrs, $class_match) === 1) {
            $class_value = $class_match[1] !== ''
                ? $class_match[1]
                : ($class_match[2] !== '' ? $class_match[2] : ($class_match[3] ?? ''));
        }
        return preg_match('/(?:^|\s)notranslate(?:\s|$)/i', trim($class_value)) === 1;
    };
    $tag_pattern = '~<!--.*?-->|<(/?)([a-z][a-z0-9:-]*)\b((?:[^"\'<>]|"[^"]*"|\'[^\']*\')*)>~isu';
    $match_count = preg_match_all($tag_pattern, $html, $matches, PREG_OFFSET_CAPTURE);
    if ($match_count === false || $match_count === 0) {
        return $html;
    }

    $stack = [];
    $ranges = [];
    foreach ($matches[0] as $index => $match) {
        $full = $match[0];
        $offset = $match[1];
        if (str_starts_with($full, '<!--')) {
            continue;
        }
        $closing = ($matches[1][$index][0] ?? '') === '/';
        $tag = strtolower((string)($matches[2][$index][0] ?? ''));
        $attrs = (string)($matches[3][$index][0] ?? '');
        if ($closing) {
            $matching_index = null;
            for ($stack_index = count($stack) - 1; $stack_index >= 0; $stack_index--) {
                if ($stack[$stack_index]['tag'] === $tag) {
                    $matching_index = $stack_index;
                    break;
                }
            }
            if ($matching_index === null) {
                continue;
            }
            $closed = array_splice($stack, $matching_index);
            $end = $offset + strlen($full);
            foreach ($closed as $entry) {
                if ($entry['ignored_start'] !== null) {
                    $ranges[] = [$entry['ignored_start'], $end];
                }
            }
            continue;
        }

        $has_active_ignore = false;
        foreach ($stack as $entry) {
            if ($entry['ignored_start'] !== null) {
                $has_active_ignore = true;
                break;
            }
        }
        $is_ignored = $is_ignored_start($attrs);
        $self_closing = preg_match('/\/\s*$/', trim($attrs)) === 1;
        if (isset($void_tags[$tag]) || $self_closing) {
            if ($is_ignored && !$has_active_ignore) {
                $ranges[] = [$offset, $offset + strlen($full)];
            }
            continue;
        }
        $stack[] = [
            'tag' => $tag,
            'ignored_start' => $is_ignored && !$has_active_ignore ? $offset : null,
        ];
    }

    usort($ranges, static function ($a, $b) {
        return $b[0] <=> $a[0];
    });
    $result = $html;
    $counter = count($protected);
    foreach ($ranges as $range) {
        [$start, $end] = $range;
        $token = "\x1AORION_I18N_IGNORE_" . $counter++ . "\x1A";
        $protected[$token] = substr($html, $start, $end - $start);
        $result = substr_replace($result, $token, $start, $end - $start);
    }
    return $result;
}

// Переводит готовый HTML. Старый вызов без второго аргумента означает RU→UK;
// output filter передаёт локаль явно.
function i18n_translate_html($html, $lang = null) {
    $lang = $lang === null ? 'uk' : i18n_locale_code($lang);
    if ($lang === 'ru') {
        return $html;
    }
    $protected = [];
    $out = i18n_protect_ignored_html($html, $protected);
    $out = i18n_replace_compiled($out, $lang);
    return $protected ? strtr($out, $protected) : $out;
}

// Переводит короткие plain-text/AJAX сообщения без необходимости собирать HTML.
function i18n_translate_text($text, $lang = null) {
    $lang = $lang === null ? current_lang() : i18n_locale_code($lang);
    if ($lang === 'ru') {
        return $text;
    }
    return i18n_replace_compiled($text, $lang);
}

// Добавляет валидный lang-параметр к относительному URL страницы. Параметр
// намеренно не удаляется: такие URL являются отдельными crawlable locale URLs.
function i18n_locale_path($path = '', $lang = null) {
    $lang = i18n_locale_code($lang === null ? current_lang() : $lang);
    $path = (string)$path;
    $fragment = '';
    $fragment_pos = strpos($path, '#');
    if ($fragment_pos !== false) {
        $fragment = substr($path, $fragment_pos);
        $path = substr($path, 0, $fragment_pos);
    }
    $query = '';
    $query_pos = strpos($path, '?');
    if ($query_pos !== false) {
        $query = substr($path, $query_pos + 1);
        $path = substr($path, 0, $query_pos);
    }
    $query_parts = $query === '' ? [] : explode('&', $query);
    $kept_parts = [];
    foreach ($query_parts as $query_part) {
        $key = $query_part;
        $equals_pos = strpos($query_part, '=');
        if ($equals_pos !== false) {
            $key = substr($query_part, 0, $equals_pos);
        }
        if (rawurldecode($key) === 'lang') {
            continue;
        }
        $kept_parts[] = $query_part;
    }
    if ($lang !== 'ru') {
        $kept_parts[] = 'lang=' . rawurlencode($lang);
    }
    return $path . ($kept_parts ? '?' . implode('&', $kept_parts) : '') . $fragment;
}

// Публичный hook для sitemap/SEO-кода: один canonical path для каждой локали.
function i18n_locale_urls($path = '') {
    $urls = [];
    foreach (i18n_locale_catalog() as $lang => $meta) {
        $urls[$lang] = i18n_locale_path($path, $lang);
    }
    return $urls;
}

// Строит URL текущей страницы с добавленным параметром ?lang=.
function i18n_switch_url($lang) {
    $lang = i18n_locale_code($lang);
    $params = $_GET;
    unset($params['lang']);
    $params['lang'] = $lang;
    $path = strtok($_SERVER['REQUEST_URI'] ?? 'index.php', '?');
    $query = http_build_query($params, '', '&', PHP_QUERY_RFC3986);
    return htmlspecialchars($path . ($query === '' ? '' : '?' . $query), ENT_QUOTES, 'UTF-8');
}

// Компактный переключатель языка для верхней панели сайта или админки.
// Оформление живёт в style.css (.lang-switch), чтобы компонент наследовал
// шрифт и цветовую тему сайта, а не задавал их инлайном.
function i18n_switcher_html($placement = 'header') {
    $placement = in_array($placement, ['header', 'admin'], true) ? $placement : 'header';
    $cur = current_lang();
    $aria = $cur === 'en' ? 'Language' : 'Язык / Мова';
    $html = '<div class="lang-switch lang-switch--' . $placement . '" role="group" aria-label="'
        . htmlspecialchars($aria, ENT_QUOTES, 'UTF-8') . '">';
    foreach (i18n_locale_catalog() as $lang => $meta) {
        $active = $cur === $lang;
        $html .= '<a href="' . i18n_switch_url($lang) . '" class="lang-switch-option'
            . ($active ? ' is-active' : '') . '"'
            . ($active ? ' aria-current="true"' : '') . '>'
            . htmlspecialchars($meta['short'], ENT_QUOTES, 'UTF-8') . '</a>';
    }
    return $html . '</div>';
}

// Колбэк output-буфера переводит страницу для выбранной локали.
// Бинарные/JSON-ответы пропускаются без изменений.
function i18n_output_filter($buffer) {
    // Не трогаем не-HTML ответы (admin.php json_out, файлы и т.п.).
    foreach (headers_list() as $h) {
        if (stripos($h, 'content-type:') === 0 && stripos($h, 'text/html') === false) {
            return $buffer;
        }
    }
    // Не трогаем фрагменты без полноценной страницы (на всякий случай).
    if (stripos($buffer, '</body>') === false && stripos($buffer, '<html') === false) {
        return $buffer;
    }
    $lang = current_lang();
    if ($lang !== 'ru') {
        $buffer = str_ireplace(['lang="ru"', "lang='ru'"], ['lang="' . $lang . '"', "lang='" . $lang . "'"] , $buffer);
        $buffer = i18n_translate_html($buffer, $lang);
    }
    return $buffer;
}
