// Возвращает только поддерживаемый код локали. При $fallback = null невалидное
// значение возвращается как null, что нужно bootstrap для очистки плохого URL.
function i18n_locale_code($lang, $fallback = 'ru') {
    $lang = strtolower(trim((string)$lang));
    $catalog = i18n_locale_catalog();
    if (isset($catalog[$lang])) {
        return $lang;
    }
    if ($fallback === null) {
        return null;
    }
    $fallback = strtolower(trim((string)$fallback));
    return isset($catalog[$fallback]) ? $fallback : 'ru';
}

function i18n_locale_meta($lang = null) {
    $code = i18n_locale_code($lang === null ? (function_exists('current_lang') ? current_lang() : 'ru') : $lang);
    return i18n_locale_catalog()[$code];
}

// Текущий язык сессии ('ru' по умолчанию, 'uk' — украинский, 'en' — английский).
function current_lang() {
    return i18n_locale_code($_SESSION['lang'] ?? 'ru');
}

